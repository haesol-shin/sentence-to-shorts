type MediaKind = 'mp4' | 'srt';

// Only two fixed resources exist. Keep their URLs valid until the page unloads,
// including when a download outlives the control that started it.
const urls: Partial<Record<MediaKind, string>> = {};

export function mockMediaUrl(kind: MediaKind): string {
  return (urls[kind] ??= URL.createObjectURL(
    kind === 'mp4'
      ? new Blob([Uint8Array.from(atob(SAMPLE_MP4), (byte) => byte.charCodeAt(0))], { type: 'video/mp4' })
      : new Blob([SAMPLE_SRT], { type: 'application/x-subrip' }),
  ));
}
